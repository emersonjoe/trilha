func lines(n int) []byte { return []byte(strings.Repeat("x := 1\n", n)) }

func find(vs []Violation, path, kind string) bool {
	for _, v := range vs {
		if v.Path == path && v.Kind == kind {
			return true
		}
	}
	return false
}

// Spec 181: a source file goes up to 500 lines and any file up to 5,000
// tokens (bytes/4); tests, docs, CSS and Markdown have no line limit.
func TestCheckLimits(t *testing.T) {
	files := map[string][]byte{
		"app/page.go":           lines(500),
		"app/grande/page.go":    lines(501),
		"internal/x/x_test.go":  lines(900),
		"public/style.css":      lines(900),
		"docs/guia.md":          lines(900),
		"web/app.ts":            lines(600),
		"web/app.spec.ts":       lines(600),
		"testdata/fixture/a.go": lines(700),
		"README.md":             []byte(strings.Repeat("a", 20_001)),
		"internal/x/tokens.go":  []byte(strings.Repeat("a", 20_000)),
		"internal/x/demais.go":  []byte(strings.Repeat("a", 20_004)),
		"internal/x/semfim.go":  []byte("a\nb"),
	}
	vs := Check(files, nil)
	for _, want := range []struct{ path, kind string }{
		{"app/grande/page.go", Lines}, {"web/app.ts", Lines},
		{"README.md", Tokens}, {"internal/x/demais.go", Tokens},
	} {
		if !find(vs, want.path, want.kind) {
			t.Errorf("%s over %s not reported: %+v", want.path, want.kind, vs)
		}
	}
	for _, ok := range []string{"app/page.go", "internal/x/x_test.go", "public/style.css", "docs/guia.md",
		"web/app.spec.ts", "testdata/fixture/a.go", "internal/x/tokens.go", "internal/x/semfim.go"} {
		for _, v := range vs {
			if v.Path == ok {
				t.Errorf("%s reported: %+v", ok, v)
			}
		}
	}
	if len(vs) != 4 {
		t.Errorf("%d violations, want 4: %+v", len(vs), vs)
	}
}

// What an agent does not write is not checked: lockfiles, generated files,
// the framework's own stamped copies, binaries, vendored code, goldens.
func TestCheckIgnoresWhatAgentsDoNotWrite(t *testing.T) {
	big := strings.Repeat("x := 1\n", 3000)
	files := map[string][]byte{
		"go.sum":                         []byte(big),
		"web/package-lock.json":          []byte(big),
		"web/yarn.lock":                  []byte(big),
		"pnpm-lock.yaml":                 []byte(big),
		"trilha_gen.go":                  []byte("// Code generated by trilha gen. DO NOT EDIT.\n\n" + big),
		"internal/api/client.go":         []byte("// Code generated by trilha client from openapi.json. DO NOT EDIT.\n" + big),
		"public/ui.js":                   []byte("/* trilha ui 0123456789abcdef */\n" + big),
		"AGENTS.md":                      []byte("<!-- trilha agents 0123456789abcdef -->\n" + big),
		"public/foto.png":                append([]byte{0x89, 'P', 'N', 'G', 0}, big...),
		"vendor/x/y.go":                  []byte(big),
		"web/node_modules/a/index.js":    []byte(big),
		"testdata/snapshots/home.golden": []byte(big),
		"public/islands.d.ts":            []byte("// Code generated by trilha gen. DO NOT EDIT.\n" + big),
		"marcado/gerado.go":              []byte(big),
	}
	generated := func(p string) bool { return p == "marcado/gerado.go" }
	if vs := Check(files, generated); len(vs) != 0 {
		t.Fatalf("checked what no agent wrote: %+v", vs)
	}
}

// Against a real repository: only what is staged counts, as it is in the
// index (not in the working tree), and .gitattributes can mark a file
// generated.
func TestStaged(t *testing.T) {
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("git not installed")
	}
	dir := t.TempDir()
	git := func(args ...string) {
		t.Helper()
		cmd := exec.Command("git", args...)
		cmd.Dir = dir
		cmd.Env = append(os.Environ(), "GIT_AUTHOR_NAME=t", "GIT_AUTHOR_EMAIL=t@example.com",
			"GIT_COMMITTER_NAME=t", "GIT_COMMITTER_EMAIL=t@example.com")
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("git %v: %v\n%s", args, err, out)
		}
	}
	write := func(p string, b []byte) {
		t.Helper()
		full := filepath.Join(dir, filepath.FromSlash(p))
		os.MkdirAll(filepath.Dir(full), 0o755)
		if err := os.WriteFile(full, b, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	git("init", "-q")
	write("velho.go", lines(900)) // committed before: not staged now
	git("add", ".")
	git("commit", "-qm", "init")

	write("novo.go", lines(501))
	write("pequeno.go", lines(10))
	write("gerado/tabela.go", lines(900))
	write(".gitattributes", []byte("gerado/** linguist-generated=true\n"))
	git("add", "novo.go", "pequeno.go", "gerado/tabela.go", ".gitattributes")
	write("pequeno.go", lines(900)) // the working tree is not what gets committed
	write("fora.go", lines(900))    // never staged

	vs, err := Staged(dir)
	if err != nil {
		t.Fatal(err)
	}
	if len(vs) != 1 || vs[0].Path != "novo.go" || vs[0].Kind != Lines || vs[0].Count != 501 {
		t.Fatalf("staged violations = %+v, want novo.go at 501 lines", vs)
	}
}

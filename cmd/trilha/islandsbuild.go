// An island that outgrows a page — a game, an editor, an engine shared with
// the server — wants TypeScript, and the kit has no bundler (#301). The
// convention is the smallest one that holds: the sources live in islands/,
// mirroring public/, with an islands/tsconfig.json; `trilha islands build`
// runs the project's own tsc into public/ and marks every file it wrote; the
// output is committed, because the Go build has no node; and --check compiles
// into a temporary directory and compares, the discipline of gen --check.

const (
	islandsSrc      = "islands"
	islandsTSConfig = "islands/tsconfig.json"
	// islandsBanner opens every file the build writes. --check finds the
	// files that belong to the build by it, so a file whose source is gone
	// is reported instead of shipped for ever.
	islandsBanner = "// Code generated by trilha islands build"
)

func cmdIslands(args []string) error {
	if len(args) == 0 || args[0] != "build" {
		return usageError{errors.New(t("islands usage"))}
	}
	fset := flag.NewFlagSet("islands build", flag.ContinueOnError)
	check := fset.Bool("check", false, t("flag islands check"))
	if err := fset.Parse(args[1:]); err != nil {
		return usageError{err}
	}
	p, err := findProject()
	if err != nil {
		return err
	}
	if *check {
		problems, err := checkIslandsBuild(p.Root)
		if err != nil {
			return err
		}
		if len(problems) > 0 {
			for _, pb := range problems {
				fmt.Fprintln(os.Stderr, pb)
			}
			return fmt.Errorf(t("islands build stale"), len(problems))
		}
		fmt.Println("✓", t("islands build fresh"))
		return nil
	}
	public := filepath.Join(p.Root, "public")
	files, err := buildIslands(p.Root, public, public)
	if err != nil {
		return err
	}
	fmt.Printf(t("islands build done"), len(files))
	return nil
}

// buildIslands compiles islands/ into out with the project's tsc and marks
// what it wrote, as if it had been written to final — the same folder, or
// public/ when --check compiles elsewhere. It returns the written paths,
// relative to out.
func buildIslands(root, out, final string) ([]string, error) {
	if _, err := os.Stat(filepath.Join(root, islandsTSConfig)); err != nil {
		return nil, fmt.Errorf(t("islands no tsconfig"), islandsTSConfig)
	}
	tsc, err := findTSC(root)
	if err != nil {
		return nil, err
	}
	cmd := exec.Command(tsc, "-p", islandsTSConfig, "--rootDir", islandsSrc, "--outDir", out, "--listEmittedFiles", "--noEmitOnError")
	cmd.Dir = root
	var stdout, stderr bytes.Buffer
	cmd.Stdout, cmd.Stderr = &stdout, &stderr
	if err := cmd.Run(); err != nil {
		return nil, fmt.Errorf("tsc: %v\n%s%s", err, withoutEmitted(stdout.String()), stderr.String())
	}
	var rels []string
	sc := bufio.NewScanner(&stdout)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if !strings.HasPrefix(line, "TSFILE:") {
			continue
		}
		abs := strings.TrimSpace(strings.TrimPrefix(line, "TSFILE:"))
		if !filepath.IsAbs(abs) {
			abs = filepath.Join(root, abs)
		}
		rel, err := filepath.Rel(out, abs)
		if err != nil || strings.HasPrefix(rel, "..") {
			continue // tsc wrote somewhere else: not ours to mark
		}
		rels = append(rels, filepath.ToSlash(rel))
	}
	sort.Strings(rels)
	emitted := map[string]bool{}
	for _, r := range rels {
		emitted[r] = true
	}
	for _, r := range rels {
		if err := markIslandFile(out, final, r, emitted); err != nil {
			return nil, err
		}
	}
	return rels, nil
}

func withoutEmitted(s string) string {
	var b strings.Builder
	for _, line := range strings.SplitAfter(s, "\n") {
		if !strings.HasPrefix(line, "TSFILE:") {
			b.WriteString(line)
		}
	}
	return b.String()
}

// markIslandFile puts the banner on a .js or .d.ts the build wrote. The banner
// pushes the code one line down, so the source map of a .js that has one gets
// one empty generated line in front of its mappings; and its sources, which
// tsc wrote relative to out, are rewritten relative to final.
func markIslandFile(out, final, rel string, emitted map[string]bool) error {
	path := filepath.Join(out, filepath.FromSlash(rel))
	if !strings.HasSuffix(rel, ".js") && !strings.HasSuffix(rel, ".mjs") && !strings.HasSuffix(rel, ".d.ts") {
		return nil
	}
	b, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	src := strings.TrimSuffix(strings.TrimSuffix(strings.TrimSuffix(rel, ".d.ts"), ".mjs"), ".js")
	banner := fmt.Sprintf("%s from %s/%s.ts. DO NOT EDIT.\n", islandsBanner, islandsSrc, src)
	if err := os.WriteFile(path, append([]byte(banner), b...), 0o644); err != nil {
		return err
	}
	if !emitted[rel+".map"] {
		return nil
	}
	mapPath := path + ".map"
	raw, err := os.ReadFile(mapPath)
	if err != nil {
		return err
	}
	var m map[string]any
	if err := json.Unmarshal(raw, &m); err != nil {
		return err
	}
	if s, ok := m["mappings"].(string); ok {
		m["mappings"] = ";" + s
	}
	if srcs, ok := m["sources"].([]any); ok {
		at := filepath.Dir(filepath.Join(final, filepath.FromSlash(rel)))
		for i, s := range srcs {
			str, ok := s.(string)
			if !ok || strings.Contains(str, "://") {
				continue
			}
			abs := filepath.Join(filepath.Dir(path), filepath.FromSlash(str))
			if r, err := filepath.Rel(at, abs); err == nil {
				srcs[i] = filepath.ToSlash(r)
			}
		}
	}
	fixed, err := json.Marshal(m)
	if err != nil {
		return err
	}
	return os.WriteFile(mapPath, fixed, 0o644)
}

// checkIslandsBuild compiles into a temporary directory and compares with
// public/: a file that differs, one the build would write and is missing, and
// one public/ still has from a source that is gone.
func checkIslandsBuild(root string) ([]string, error) {
	tmp, err := os.MkdirTemp("", "trilha-islands-")
	if err != nil {
		return nil, err
	}
	defer os.RemoveAll(tmp)
	public := filepath.Join(root, "public")
	rels, err := buildIslands(root, tmp, public)
	if err != nil {
		return nil, err
	}
	var problems []string
	built := map[string]bool{}
	for _, r := range rels {
		built[r] = true
		want, _ := os.ReadFile(filepath.Join(tmp, filepath.FromSlash(r)))
		got, err := os.ReadFile(filepath.Join(public, filepath.FromSlash(r)))
		switch {
		case err != nil:
			problems = append(problems, fmt.Sprintf(t("islands build missing"), "public/"+r))
		case !bytes.Equal(got, want):
			problems = append(problems, fmt.Sprintf(t("islands build differs"), "public/"+r))
		}
	}
	_ = filepath.WalkDir(public, func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return nil
		}
		rel, _ := filepath.Rel(public, path)
		rel = filepath.ToSlash(rel)
		if built[rel] {
			return nil
		}
		f, err := os.Open(path)
		if err != nil {
			return nil
		}
		head := make([]byte, len(islandsBanner))
		n, _ := f.Read(head)
		f.Close()
		if string(head[:n]) == islandsBanner {
			problems = append(problems, fmt.Sprintf(t("islands build orphan"), "public/"+rel))
		}
		return nil
	})
	sort.Strings(problems)
	return problems, nil
}

// findTSC is the compiler the project chose: TRILHA_TSC, then the one npm
// installed in node_modules, then the PATH. The kit brings none.
func findTSC(root string) (string, error) {
	if p := os.Getenv("TRILHA_TSC"); p != "" {
		return p, nil
	}
	local := filepath.Join(root, "node_modules", ".bin", "tsc")
	if runtime.GOOS == "windows" {
		local += ".cmd"
	}
	if _, err := os.Stat(local); err == nil {
		return local, nil
	}
	if p, err := exec.LookPath("tsc"); err == nil {
		return p, nil
	}
	return "", errors.New(t("islands no tsc"))
}

// checkStepIslands is the gate of trilha check: skipped for a project without
// islands/tsconfig.json, failed when the committed output is not what the
// sources compile to — or when there is no tsc to tell.
func checkStepIslands(p *project, _ bool) (string, []problem) {
	if _, err := os.Stat(filepath.Join(p.Root, islandsTSConfig)); err != nil {
		return statusSkipped, nil
	}
	problems, err := checkIslandsBuild(p.Root)
	if err != nil {
		return statusFailed, []problem{{Tool: "islands", File: islandsTSConfig, Message: err.Error(), Fix: t("fix islands build")}}
	}
	if len(problems) == 0 {
		return statusOK, nil
	}
	var out []problem
	for _, m := range problems {
		out = append(out, problem{Tool: "islands", Message: m, Fix: t("fix islands build")})
	}
	return statusFailed, out
}
